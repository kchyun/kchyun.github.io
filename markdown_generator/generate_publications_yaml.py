#!/usr/bin/env python3
"""
Generate _data/publications.yml from front matter of all Markdown files
inside the _publications directory (no Jekyll plugin needed).

Usage (from repo root):
  python markdown_generator/generate_publications_yaml.py

Steps:
 1. Scan _publications/*.md
 2. Parse YAML front matter (fallback simple parser if PyYAML absent)
 3. Extract keys: title, date, venue, excerpt, citation, paperurl/slidesurl,
    teaser_img, category, permalink
 4. If teaser_img missing, attempt to grab first <img src="..."> in body
 5. Sort by date descending
 6. Write _data/publications.yml

No external dependency strictly required; if PyYAML present it'll produce
cleaner output. Otherwise a minimal emitter is used.
"""
from __future__ import annotations
import re
import sys
from pathlib import Path
from datetime import datetime
from typing import Any, Dict, List

ROOT = Path(__file__).resolve().parent.parent  # project root
PUB_DIR = ROOT / '_publications'
DATA_DIR = ROOT / '_data'
OUT_FILE = DATA_DIR / 'publications.yml'

FRONT_MATTER_RE = re.compile(r'^---\s*\n(.*?)\n---\s*\n?', re.DOTALL)
IMG_RE = re.compile(r'<img[^>]*src=["\']([^"\']+)["\']', re.IGNORECASE)

NEEDED_KEYS_ORDER = [
    'title', 'authors', 'pub_date', 'date', 'venue', 'excerpt', 'citation',
    'paper_url', 'slides_url', 'code_url', 'teaser_img', 'category', 'permalink', 'arxiv_icon', 'github_icon',
]


def load_yaml_if_available():
    try:
        import yaml  # type: ignore
        return yaml
    except Exception:
        return None


def parse_front_matter(text: str) -> Dict[str, Any]:
    match = FRONT_MATTER_RE.match(text)
    if not match:
        return {}
    fm_text = match.group(1)
    ylib = load_yaml_if_available()
    if ylib:
        try:
            data = ylib.safe_load(fm_text) or {}
            if isinstance(data, dict):
                return data
        except Exception:
            pass  # fallback to naive parser
    # naive parse: key: value lines only
    data: Dict[str, Any] = {}
    for line in fm_text.splitlines():
        line = line.strip()
        if not line or line.startswith('#'):
            continue
        if ':' not in line:
            continue
        key, val = line.split(':', 1)
        key = key.strip()
        val = val.strip().strip('"').strip("'")
        data[key] = val
    return data


def extract_body(text: str) -> str:
    match = FRONT_MATTER_RE.match(text)
    if not match:
        return text
    return text[match.end():]


def coerce_date(val: Any) -> str:
    if not val:
        return ''
    if isinstance(val, datetime):
        return val.strftime('%Y-%m-%d')
    s = str(val).strip()
    # Accept YYYY-MM-DD only
    try:
        dt = datetime.strptime(s[:10], '%Y-%m-%d')
        return dt.strftime('%Y-%m-%d')
    except Exception:
        return s


def collect_publications() -> List[Dict[str, Any]]:
    pubs: List[Dict[str, Any]] = []
    if not PUB_DIR.exists():
        print(f"[WARN] Directory not found: {PUB_DIR}", file=sys.stderr)
        return pubs
    for md_file in sorted(PUB_DIR.glob('*.md')):
        raw = md_file.read_text(encoding='utf-8')
        fm = parse_front_matter(raw)
        body = extract_body(raw)
        teaser = fm.get('teaser_img') or fm.get('teaser') or ''
        if not teaser:
            m = IMG_RE.search(body)
            if m:
                teaser = m.group(1)
        item = {
            'title': fm.get('title'),
            'pub_date': coerce_date(fm.get('date')),  # alias used previously
            'authors': fm.get('authors'),
            'date': coerce_date(fm.get('date')),
            'venue': fm.get('venue'),
            'excerpt': fm.get('excerpt'),
            'citation': fm.get('citation'),
            'paper_url': fm.get('paperurl') or fm.get('paper_url'),
            'slides_url': fm.get('slidesurl') or fm.get('slides_url'),
            'code_url': fm.get('codeurl') or fm.get('code_url'),
            'teaser_img': teaser,
            'category': fm.get('category'),
            'permalink': fm.get('permalink'),
            'arxiv_icon': fm.get('arxiv_icon'),
            'github_icon': fm.get('github_icon'),
        }
        pubs.append(item)
    # sort descending by date
    pubs.sort(key=lambda x: x.get('pub_date') or '', reverse=True)
    return pubs


def emit_yaml(pubs: List[Dict[str, Any]]) -> str:
    ylib = load_yaml_if_available()
    ordered_pubs: List[Dict[str, Any]] = []
    for p in pubs:
        ordered: Dict[str, Any] = {}
        for k in NEEDED_KEYS_ORDER:
            if p.get(k) is not None:
                ordered[k] = p.get(k)
        # include any extra keys at end
        for k, v in p.items():
            if k not in ordered:
                ordered[k] = v
        ordered_pubs.append(ordered)
    if ylib:
        return '# Generated by generate_publications_yaml.py\n' + ylib.safe_dump(ordered_pubs, sort_keys=False, allow_unicode=True)
    # fallback naive yaml
    lines: List[str] = ['# Generated by generate_publications_yaml.py']
    for p in ordered_pubs:
        lines.append('-')
        for k, v in p.items():
            if v is None or v == '':
                continue
            sv = str(v)
            if any(c in sv for c in [':', '#', '{', '}', '[', ']', ',', '"', "'", '\n']):
                sv_escaped = sv.replace('"', '\"')
                lines.append(f"  {k}: \"{sv_escaped}\"")
            else:
                lines.append(f"  {k}: {sv}")
    return '\n'.join(lines) + '\n'


def main():
    pubs = collect_publications()
    DATA_DIR.mkdir(parents=True, exist_ok=True)
    yaml_text = emit_yaml(pubs)
    OUT_FILE.write_text(yaml_text, encoding='utf-8')
    print(f"Wrote {len(pubs)} publication record(s) -> {OUT_FILE}")


if __name__ == '__main__':
    main()
